import type { useDatabaseSession } from "@/features/connection/hooks/useDatabaseSession";
import { usePendingEdits } from "@/features/tables/hooks/usePendingEdits";
import { useTableData } from "@/features/tables/hooks/useTableData";
import { useProjectDialogs } from "@/features/project/hooks/useProjectDialogs";
import { useQueryEditor } from "@/features/query/hooks/useQueryEditor";
import { useTableDetails } from "@/features/schema/hooks/useTableDetails";
import { useExport } from "@/features/workspace/hooks/useExport";
import { useSchemaActions } from "@/features/schema/hooks/useSchemaActions";
import { useOpenDatabaseShortcut } from "@/features/workspace/hooks/useOpenDatabaseShortcut";
import { useWorkspaceState } from "@/features/workspace/hooks/useWorkspaceState";
import { useWorkspaceSync } from "@/features/workspace/hooks/useWorkspaceSync";

type DatabaseSession = ReturnType<typeof useDatabaseSession>;

export function useWorkspaceController(session: DatabaseSession) {
  const {
    db,
    loading: sessionLoading,
    error,
    setError,
    notice,
    setNotice,
    showDesignerOnOpen,
    recentDatabases,
    missingRecents,
    clearRecentDatabases,
    openRecentDatabase,
    removeRecentDatabase,
    openDb,
    createNewDatabase,
  } = session;
  const {
    tables,
    setTables,
    showDesigner,
    setShowDesigner,
    view,
    setView,
    schema,
    setSchema,
    schemaGraph,
    setSchemaGraph,
    showAlterTable,
    setShowAlterTable,
    creatingBackup,
    setCreatingBackup,
    restoringBackup,
    setRestoringBackup,
    exportFormat,
    setExportFormat,
    exporting,
    setExporting,
    initialized,
    lastDataVersion,
    externalChangePending,
    saveReloadRef,
    pendingGuardRef,
    pendingResetRef,
  } = useWorkspaceState(db?.tables ?? [], showDesignerOnOpen);


  const {
    tableDetails,
    setTableDetails,
    tableStats,
    setTableStats,
    detailsLoading,
    loadDetails,
    resetTableDetails,
  } = useTableDetails({ setError });

  const {
    selected,
    setSelected,
    columns,
    setColumns,
    foreignKeys,
    setForeignKeys,
    page,
    setPage,
    pageSize,
    history,
    setHistory,
    historyIndex,
    setHistoryIndex,
    pageIndex,
    setPageIndex,
    count,
    setCount,
    loading,
    sort,
    setSort,
    dataFilter,
    setDataFilter,
    filterDraft,
    setFilterDraft,
    pagedMode,
    currentPage,
    rowStart,
    rowEnd,
    nextDisabled,
    prevDisabled,
    loadTable,
    loadOffsetPage,
    selectTable,
    toggleSort,
    applyFilter,
    clearFilter,
    nextPage,
    prevPage,
    changePageSize,
    reloadCurrent,
    reloadTable,
    clearTable,
  } = useTableData({
    currentView: view,
    guardPending: () => pendingGuardRef.current(),
    resetTableUi: () => pendingResetRef.current(),
    resetTableDetails,
    setView,
    setError,
  });

  const busy = loading || sessionLoading;

  const {
    selectedRow,
    setSelectedRow,
    selectionKeys,
    pendingInserts,
    pendingUpdates,
    pendingDeletes,
    rowEditor,
    setRowEditor,
    saving,
    hasPending,
    pendingRowIds,
    displayRows,
    allSelected,
    someSelected,
    guardPending,
    resetTableUi,
    discardChanges,
    clearSelection,
    toggleRowSelection,
    toggleAllSelection,
    copySelectedRows,
    deleteSelectedRows,
    handleCellCommit,
    canEditCell,
    pasteIntoCell,
    saveChanges,
    submitRowEditor,
    editSelectedRow,
    deleteSelectedRow,
  } = usePendingEdits({
    page,
    columns,
    selected,
    view,
    restoringBackup,
    setNotice,
    setError,
    onAfterSave: () => saveReloadRef.current(),
  });
  pendingGuardRef.current = guardPending;
  pendingResetRef.current = resetTableUi;

  const {
    queryResult,
    queryRunning,
    queryPlan,
    setQueryPlan,
    explainRunning,
    queryLimit,
    setQueryLimit,
    queryHistory,
    runQuery,
    explainQuery,
    changeSqlText,
  } = useQueryEditor({ setView, setSelectedRow, setError });

  useWorkspaceSync({
    db,
    dbPath: db?.path ?? null,
    view,
    selected,
    pagedMode,
    pageIndex,
    sort,
    dataFilter,
    history,
    historyIndex,
    loading,
    queryRunning,
    saving,
    restoringBackup,
    hasPending,
    loadTable,
    loadOffsetPage,
    loadDetails,
    setCount,
    setNotice,
    setTables,
    setSchema,
    setSchemaGraph,
    setSelected,
    setPage,
    setColumns,
    setTableDetails,
    setTableStats,
    initialized,
    lastDataVersion,
    externalChangePending,
    saveReloadRef,
  });

  const {
    handleTableCreated,
    requestDesigner,
    refreshAfterSchemaChange,
    refresh,
    switchView,
    requestAlterTable,
    handleAlterApplied,
    handleCreateIndex,
    handleDropIndex,
    openForeignKey,
    openReferencedTable,
  } = useSchemaActions({
    setShowDesigner,
    setShowAlterTable,
    setTables,
    setSchema,
    setSchemaGraph,
    setView,
    setSort,
    setDataFilter,
    setFilterDraft,
    setPageIndex,
    resetTableUi,
    setHistory,
    setHistoryIndex,
    setSelected,
    setPage,
    setColumns,
    setForeignKeys,
    setCount,
    setTableDetails,
    setTableStats,
    setSelectedRow,
    setError,
    setNotice,
    guardPending,
    loadTable,
    loadOffsetPage,
    loadDetails,
    reloadCurrent,
    runQuery,
    lastDataVersion,
    externalChangePending,
    selected,
    view,
    pagedMode,
    pageIndex,
    sort,
    dataFilter,
    history,
    historyIndex,
    schemaGraph,
  });

  const {
    showMigrations,
    setShowMigrations,
    migrations,
    migrationsLoading,
    migrationsApplying,
    migrationsError,
    showBackups,
    setShowBackups,
    showImport,
    setShowImport,
    showD1Export,
    setShowD1Export,
    backups,
    backupsLoading,
    backupsError,
    loadMigrations,
    loadBackups,
    openMigrations,
    handleApplyMigrations,
    openBackups,
    handleCreateBackup,
    requestImport,
    handleImported,
    requestD1Export,
    handleD1Exported,
    handleRestoreBackup,
  } = useProjectDialogs({
    guardPending,
    refreshAfterSchemaChange,
    openReferencedTable,
    selected,
    setNotice,
    creatingBackup,
    setCreatingBackup,
    restoringBackup,
    setRestoringBackup,
  });

  useOpenDatabaseShortcut(openDb);

  const exportCurrent = useExport({
    exporting,
    setExporting,
    guardPending,
    view,
    selected,
    exportFormat,
    dataFilter,
    sort,
    setError,
    setNotice,
  });

  const detailColumns = view === "data" ? columns : (queryResult?.columns ?? []);


  return {
    db,
    sessionLoading,
    error,
    setError,
    notice,
    setNotice,
    recentDatabases,
    missingRecents,
    clearRecentDatabases,
    openRecentDatabase,
    removeRecentDatabase,
    openDb,
    createNewDatabase,
    tables,
    setTables,
    showDesigner,
    setShowDesigner,
    view,
    setView,
    schema,
    setSchema,
    schemaGraph,
    setSchemaGraph,
    showAlterTable,
    setShowAlterTable,
    creatingBackup,
    restoringBackup,
    exportFormat,
    setExportFormat,
    exporting,
    selected,
    setSelected,
    columns,
    setColumns,
    foreignKeys,
    setForeignKeys,
    page,
    setPage,
    pageSize,
    history,
    setHistory,
    historyIndex,
    setHistoryIndex,
    pageIndex,
    setPageIndex,
    count,
    setCount,
    loading,
    sort,
    setSort,
    dataFilter,
    setDataFilter,
    filterDraft,
    setFilterDraft,
    pagedMode,
    currentPage,
    rowStart,
    rowEnd,
    nextDisabled,
    prevDisabled,
    loadTable,
    loadOffsetPage,
    selectTable,
    toggleSort,
    applyFilter,
    clearFilter,
    nextPage,
    prevPage,
    changePageSize,
    reloadCurrent,
    reloadTable,
    clearTable,
    selectedRow,
    setSelectedRow,
    selectionKeys,
    pendingInserts,
    pendingUpdates,
    pendingDeletes,
    rowEditor,
    setRowEditor,
    saving,
    hasPending,
    pendingRowIds,
    displayRows,
    allSelected,
    someSelected,
    guardPending,
    resetTableUi,
    discardChanges,
    clearSelection,
    toggleRowSelection,
    toggleAllSelection,
    copySelectedRows,
    deleteSelectedRows,
    handleCellCommit,
    canEditCell,
    pasteIntoCell,
    saveChanges,
    submitRowEditor,
    editSelectedRow,
    deleteSelectedRow,
    queryResult,
    queryRunning,
    queryPlan,
    setQueryPlan,
    explainRunning,
    queryLimit,
    setQueryLimit,
    queryHistory,
    runQuery,
    explainQuery,
    changeSqlText,
    tableDetails,
    setTableDetails,
    tableStats,
    setTableStats,
    detailsLoading,
    loadDetails,
    resetTableDetails,
    showMigrations,
    setShowMigrations,
    migrations,
    migrationsLoading,
    migrationsApplying,
    migrationsError,
    showBackups,
    setShowBackups,
    showImport,
    setShowImport,
    showD1Export,
    setShowD1Export,
    backups,
    backupsLoading,
    backupsError,
    loadMigrations,
    loadBackups,
    openMigrations,
    handleApplyMigrations,
    openBackups,
    handleCreateBackup,
    requestImport,
    handleImported,
    requestD1Export,
    handleD1Exported,
    handleRestoreBackup,
    busy,
    detailColumns,
    refreshAfterSchemaChange,
    exportCurrent,
    refresh,
    switchView,
    requestDesigner,
    requestAlterTable,
    handleAlterApplied,
    handleCreateIndex,
    handleDropIndex,
    openForeignKey,
    openReferencedTable,
    handleTableCreated,
  };
}
